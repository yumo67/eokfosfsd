export function iconCanvas(name, color = P.ink, red = P.red, scale = 1) {
  const rows = B[name] || B.task; const cv = document.createElement('canvas'); cv.width = 9 * scale; cv.height = 9 * scale; cv.className = 'ico';
  const g = cv.getContext('2d');
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === '.') return; g.fillStyle = c === 'r' ? red : color; g.fillRect(x * scale, y * scale, scale, scale); }));
  return cv;
}
